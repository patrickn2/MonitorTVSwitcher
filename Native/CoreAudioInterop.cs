using System.Runtime.InteropServices;

namespace MonitorTVSwitcher.Native;

internal static class CoreAudioInterop
{
    public static readonly Guid MmDeviceEnumeratorClsid = new("BCDE0395-E52F-467C-8E3D-C4579291692E");
    public static readonly PropertyKey PkeyDeviceFriendlyName = new(new Guid("A45C254E-DF1C-4EFD-8020-67D146A850E0"), 14);

    public const uint DeviceStateActive = 0x00000001;
    public const ushort VtLpWStr = 31;

    [DllImport("ole32.dll")]
    public static extern int PropVariantClear(ref PropVariant pvar);

    public static object CreateEnumerator()
    {
        var type = Type.GetTypeFromCLSID(MmDeviceEnumeratorClsid)
            ?? throw new InvalidOperationException("MMDeviceEnumerator COM class is unavailable.");
        return Activator.CreateInstance(type)
            ?? throw new InvalidOperationException("Could not create MMDeviceEnumerator.");
    }
}

internal enum EDataFlow
{
    Render = 0,
    Capture = 1,
    All = 2
}

internal enum ERole
{
    Console = 0,
    Multimedia = 1,
    Communications = 2
}

[StructLayout(LayoutKind.Sequential)]
internal struct PropertyKey
{
    public Guid Fmtid;
    public uint Pid;

    public PropertyKey(Guid fmtid, uint pid)
    {
        Fmtid = fmtid;
        Pid = pid;
    }
}

[StructLayout(LayoutKind.Sequential)]
internal struct PropVariant
{
    public ushort vt;
    public ushort wReserved1;
    public ushort wReserved2;
    public ushort wReserved3;
    public IntPtr Data;
    public IntPtr Data2;
}

